function shape(resolved: ReturnType<typeof resolveBlockDNA>): LegacyGolden {
  return {
    dnaId: resolved.dna.id,
    zoneLayout: resolved.zoneLayout,
    incomeMultiplier: resolved.incomeMultiplier,
    heatDecayMultiplier: resolved.dna.heatDecayMultiplier,
    globalCoverBonus: resolved.dna.globalCoverBonus,
    startingMorale: resolved.startingMorale,
    maxMembers: resolved.maxMembers,
    startingHeat: resolved.startingHeat,
    hotBlock: resolved.dna.hotBlock,
  };
}

describe('frozen v1 resolver catalog', () => {
  it('holds exactly the 25 pre-batch-two cards', () => {
    expect(RESOLVER_CATALOG_V1_IDS).toHaveLength(25);
    expect(new Set(RESOLVER_CATALOG_V1_IDS).size).toBe(25);
    expect(getResolverCatalog('v1')).toHaveLength(25);
  });

  it('still resolves every frozen id against the live library', () => {
    const liveIds = new Set(BLOCK_DNA_LIBRARY.map((dna) => dna.id));
    const missing = RESOLVER_CATALOG_V1_IDS.filter((id) => !liveIds.has(id));
    expect(missing).toEqual([]);
  });

  it('excludes batch-two cards from the v1 pool', () => {
    const v1Ids = new Set(getResolverCatalog('v1').map((dna) => dna.id));
    for (const id of BATCH_TWO_IDS) expect(v1Ids.has(id)).toBe(false);
  });

  it('keeps batch-two cards reachable in the current catalog', () => {
    expect(CURRENT_RESOLVER_CATALOG_VERSION).toBe('v2');
    const liveIds = new Set(getResolverCatalog().map((dna) => dna.id));
    for (const id of BATCH_TWO_IDS) expect(liveIds.has(id)).toBe(true);
    expect(getResolverCatalog()).toHaveLength(BLOCK_DNA_LIBRARY.length);
  });

  it('does not shrink the v1 pool when the library grows', () => {
    expect(BLOCK_DNA_LIBRARY.length).toBeGreaterThan(getResolverCatalog('v1').length);
  });
});

describe('legacy resolution contract', () => {
  it.each(LEGACY_CASES)(
    'reproduces the pre-batch-two result for $key',
    ({ lat, lng, address, golden }) => {
      expect(shape(resolveBlockDNA(lat, lng, address, 'v1'))).toEqual(golden);
    },
  );

  it('resolveLegacyBlockDNA is the v1-pinned resolver', () => {
    for (const c of LEGACY_CASES) {
      expect(shape(resolveLegacyBlockDNA(c.lat, c.lng, c.address))).toEqual(
        shape(resolveBlockDNA(c.lat, c.lng, c.address, 'v1')),
      );
    }
  });

  it('reports the catalog version it resolved under', () => {
    const c = LEGACY_CASES[0];
    expect(resolveBlockDNA(c.lat, c.lng, c.address, 'v1').catalogVersion).toBe('v1');
    expect(resolveBlockDNA(c.lat, c.lng, c.address).catalogVersion).toBe('v2');
  });

  /**
   * Guard rail. If this ever fails, the expanded catalog stopped changing
   * generic resolution — at which point someone may be tempted to delete the
   * pinning. Do not. Re-derive the goldens instead and keep the versioning.
   */
  it('demonstrates that the live catalog WOULD move these blocks', () => {
    const moved = LEGACY_CASES.filter(
      (c) => resolveBlockDNA(c.lat, c.lng, c.address).dna.id !== c.golden.dnaId,
    );
    expect(moved.length).toBeGreaterThan(0);
  });
});
