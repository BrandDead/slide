/**
 * Block DNA legacy resolver contract.
 *
 * WHY THIS FILE EXISTS
 * The generic resolver picks a DNA by indexing into catalog-derived arrays
 * (`seedNum % matches.length`, nearest-by-distance, `seed % catalog.length`).
 * All three are sensitive to catalog MEMBERSHIP, so appending cards to
 * BLOCK_DNA_LIBRARY silently re-resolves blocks a player already claimed —
 * changing their tactical layout, income, heat decay, cover, morale and
 * capacity on reload.
 *
 * Measured at the time batch two was written: 485 of 610 sampled generic
 * locations resolved to a DIFFERENT card once the catalog grew from 25 to 33.
 *
 * The guarantee this file locks down: a block claimed under catalog v1 always
 * re-resolves to the same v1 result, no matter how large the live library
 * becomes. The goldens below were generated by running the pre-batch-two
 * resolver (origin/main-tL2525) and must never be edited to make a test pass.
 */

